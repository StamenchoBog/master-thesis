def mk(v, d=1):
    """Macedonian number format: decimal comma, thin-space thousands."""
    return f"{v:,.{d}f}".replace(",", "X").replace(".", "{,}").replace("X", "\\,")


def pts(xs, ys):
    return " ".join(f"({x:.6g},{y:.6g})" for x, y in zip(xs, ys))


def figure(header, body, caption, label):
    return (f"% Generated by analysis/make_figures.py from {header}.\n" + COLORS
            + "\\begin{figure}[htbp]\n\\centering\n\\begin{tikzpicture}\n" + body
            + f"\\end{{tikzpicture}}\n\\caption{caption}\n\\label{{{label}}}\n\\end{{figure}}\n")


def campaign():
    s = pd.read_csv(f"{T}/campaign_summary.csv")
    return s[s.run.str.match(r"(naive|sisa)_seed\d+$")]


