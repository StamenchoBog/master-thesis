def phase3_trace(pre=20, post=20):
    tr = {}
    for arm in ("naive", "sisa"):
        d = f"results/msc/campaign/{arm}_seed42"
        t = pd.read_csv(glob.glob(f"{d}/hardware_telemetry_*.csv")[0])
        p3 = t[t.Marker == "phase3"]
        t0, t1 = p3.Epoch_s.min(), p3.Epoch_s.max()
        w = t[(t.Epoch_s >= t0 - pre) & (t.Epoch_s <= t1 + post)].copy()
        w["x"] = w.Epoch_s - t0
        w["thr"] = w.Throttled.apply(lambda h: (int(h, 16) & 0xE) != 0)
        pw = pd.read_csv(f"{d}/power_fnb58.csv", sep=r"\s+")
        pw = pw[(pw.timestamp >= t0 - pre) & (pw.timestamp < t1 + post + 1)].copy()
        pw["x"] = (pw.timestamp - t0).astype(int)
        pw["W"] = pw.voltage_V * pw.current_A
        tr[arm] = dict(t1=t1 - t0, temp=w[["x", "Temp_C"]].values.tolist(),
                       thr=w[w.thr].x.tolist(), pw=list(pw.groupby("x").W.mean().items()))
    xmax = max(v["t1"] for v in tr.values()) + post

    def coords(pairs, d=2):
        return " ".join(f"({int(x)},{y:.{d}f})" for x, y in pairs)

    common = (f"scale only axis, width=0.84\\linewidth, xmin={-pre}, xmax={xmax}, "
              "axis line style={gray!60}, tick style={gray!60}, ymajorgrids, grid style={gray!20}, "
              "tick label style={font=\\small}, label style={font=\\small}, scaled ticks=false, "
              "every axis y label/.style={at={(rel axis cs:-0.1,0.5)}, rotate=90, anchor=south, "
              "font=\\small}")

    def panel(body, opts, name, below=None, last=False):
        pos = f", at={{({below}.south west)}}, anchor=north west, yshift=-0.35cm" if below else ""
        xl = ", xlabel={Време од почетокот на Фаза 3 (s)}" if last else ", xticklabels={}"
        ends = "".join(f"\\draw[{col}, densely dotted, line width=0.9pt] "
                       f"({{axis cs:{tr[arm]['t1']},0}} |- {{rel axis cs:0,0}}) -- "
                       f"({{axis cs:{tr[arm]['t1']},0}} |- {{rel axis cs:0,1}});\n"
                       for arm, col in (("naive", "naivecol"), ("sisa", "sisacol")))
        head = f"\\begin{{axis}}[{common}, name={name}{pos}, {opts}{xl}]\n"
        return f"{head}{body}{ends}\\end{{axis}}\n"

    power = ("\\addplot[color=naivecol, line width=1pt] coordinates "
             f"{{{coords(tr['naive']['pw'])}}};\n\\addlegendentry{{Наивно повторно тренирање}}\n"
             "\\addplot[color=sisacol, line width=1pt, densely dashed] coordinates "
             f"{{{coords(tr['sisa']['pw'])}}};\n\\addlegendentry{{SISA}}\n")
    temp = (f"\\addplot[color=naivecol, line width=1pt] coordinates "
            f"{{{coords(tr['naive']['temp'], 1)}}};\n"
            "\\addplot[color=sisacol, line width=1pt, densely dashed] coordinates "
            f"{{{coords(tr['sisa']['temp'], 1)}}};\n")
    throttled = "".join(
        f"\\addplot[only marks, mark=|, mark size=3pt, color={col}] coordinates "
        f"{{{' '.join(f'({int(x)},{y})' for x in tr[arm]['thr'])}}};\n"
        for arm, col, y in (("naive", "naivecol", 1), ("sisa", "sisacol", 0)))
    legend = ("legend style={at={(0.5,1.05)}, anchor=south, legend columns=2, draw=none, "
              "font=\\small, /tikz/every even column/.append style={column sep=1.2em}}")
    body = (panel(power, "height=3.2cm, ylabel={Моќност (W)}, ymin=2.5, ymax=7, " + legend, "pw")
            + panel(temp, "height=3.2cm, ylabel={Температура (\\textdegree C)}, ymin=68, ymax=92",
                    "tp", "pw")
            + panel(throttled, "height=1.3cm, ymin=-0.6, ymax=1.6, ytick={0,1}, "
                    "yticklabels={SISA, Наивно}, ymajorgrids=false, "
                    "title={Секунди со активно термичко придушување}, "
                    "title style={font=\\small, yshift=-0.5ex}, yshift=-0.5cm", "th", "tp", True))
    return figure("results/msc/campaign/{naive,sisa}_seed42 (power at 1 s means, telemetry 1 Hz)",
                  body, "[Моќност, температура и термичко придушување во Фаза 3]{Моќност, "
                  "температура и термичко придушување во Фаза 3 (почетна вредност 42, двата "
                  "пристапа во иста сесија). Точкестите линии го означуваат крајот на прозорецот "
                  "на секој пристап.}", "fig:phase3-trace")


def model_size_data():
    pred = pd.read_csv(f"{T}/model_size_predictions.csv").sort_values("params")
    meas = pd.read_csv(f"{T}/model_size_measurements.csv")
    c = campaign()
    measured = {arm: [(12865, c[c.arm == arm].ttr_s.median())] for arm in ("naive", "sisa")}
    for w, p in ((384, 100033), (1280, 1050241), (4096, 10569729)):
        for arm in ("naive", "sisa"):
            path = f"results/msc/model_size/validation/w{w}_{arm}_seed42/recovery_manifest.json"
            measured[arm].append((p, json.load(open(path))["total_s"]))
    write_s = meas.groupby("width").ckpt_write_median_s.median()
    io = [100 * SISA_CKPTS * write_s[w] / t for w, t in zip(pred.width, pred.t_sisa_s)]
    return pred, meas, measured, io


def model_size(pred, meas, measured, io):
    slope, icpt = np.polyfit(meas.params, meas.ckpt_bytes, 1)
    limit = (FREE_GB * 1e9 / 250 - icpt) / slope
    grid = np.logspace(4, 8, 30)
    mark = "mark options={draw=white, line width=0.5pt}"
    measured_speedup = [n / s for (_, n), (_, s) in zip(measured["naive"], measured["sisa"])]
    left = (
        "\\begin{axis}[name=ttr, scale only axis, width=0.32\\linewidth, height=5cm, xmode=log, "
        "xmin=5e3, xmax=3e7, ymin=6.5, ymax=9, axis y line*=left, xlabel={Број на параметри $P$}, "
        f"ylabel={{Забрзување на SISA}}, ymajorgrids, {AXIS}]\n"
        "\\addplot[gray, densely dashed, line width=0.8pt] coordinates "
        f"{{(5e3,{WORK_RATIO:.3f}) (3e7,{WORK_RATIO:.3f})}};\n"
        f"\\node[anchor=south west, font=\\scriptsize, gray] at (axis cs:6e3,{WORK_RATIO:.3f}) "
        f"{{однос на обемот на пресметки ({mk(WORK_RATIO, 2)})}};\n"
        f"\\addplot[color=sisacol, line width=0.9pt, mark=square*, mark size=2.2pt, {mark}] "
        f"coordinates {{{pts(pred.params, pred.speedup)}}};\n"
        f"\\addplot[only marks, mark=square*, mark size=2.4pt, color=black!70, {mark}] "
        f"coordinates {{{pts([p for p, _ in measured['naive']], measured_speedup)}}};\n"
        f"\\node[anchor=north east, font=\\scriptsize, sisacol] at "
        f"(axis cs:1.2e7,{pred.speedup.iloc[-1]:.3f}) {{забрзување (модел; квадрати: мерење)}};\n"
        "\\end{axis}\n"
        "\\begin{axis}[at={(ttr.south west)}, anchor=south west, scale only axis, "
        "width=0.32\\linewidth, height=5cm, xmode=log, xmin=5e3, xmax=3e7, ymin=0, ymax=20, "
        f"axis y line*=right, axis x line=none, ylabel={{Удел на запишувањето (\\%)}}, {AXIS}]\n"
        "\\addplot[color=black!60, densely dashed, line width=0.9pt, mark=o, mark size=2.2pt, "
        f"mark options={{solid}}] coordinates {{{pts(pred.params, io)}}};\n"
        f"\\node[anchor=south east, font=\\scriptsize, black!60] at (axis cs:1.2e7,{io[-1]:.2f}) "
        "{удел на запишувањето};\n\\end{axis}\n")
